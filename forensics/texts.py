"""Stage-C explanation targets for forensics/index.py records, in the self-explaining format.

CASIA v2 and SD_inpaint use the MMTD-Set-34k descriptions (FakeShield), matched by file stem; MMTD's
own questions name the suspected manipulation, so the open question below replaces them. Sources
without texts get grounded descriptions from the ground-truth mask: forgery type, the face parts
(MediaPipe) or image area the mask covers, and its size. These never claim artifacts that are not
in the labels, so they are correct about *what* and *where* but deliberately plain.

python -m forensics.texts --index ../data/index/openforensics.jsonl --roots openforensics=... \
    --mmtd ../data/MMTD-Set-34k/MMTD-Set-34k.json --out ../data/stagec/openforensics.json
"""
import argparse
import json
import os
import random

import numpy as np

from forensics.data import ForgeryDataset, load_index
from forensics.index import TYPES

QUESTIONS = [
    'Is this image real or fake? Explain why and point out any manipulated region.',
    'Determine the authenticity of this image. If it was manipulated, describe how and where.',
    'Is this face real or fake? Explain which regions show the manipulation, if any.',
]
TYPE_TEXT = {
    'face_swap': 'The face has been replaced with another identity (a face-swap or reenactment deepfake).',
    'splice': 'Content has been pasted in from another image or duplicated within the image (splicing / copy-move).',
    'diffusion_local': 'Part of the image has been regenerated by a diffusion inpainting model.',
    'img2img': 'The whole face has been re-rendered by a diffusion model starting from a real photo.',
    'generated': 'The entire face is synthetic, produced by an image generator rather than a camera.',
}


def _join(xs):
    return xs[0] if len(xs) == 1 else ', '.join(xs[:-1]) + ' and ' + xs[-1]


def _position(mask):
    ys, xs = np.nonzero(mask)
    cy, cx = ys.mean() / mask.shape[0], xs.mean() / mask.shape[1]
    v = 'upper' if cy < 0.33 else 'lower' if cy > 0.66 else 'middle'
    h = 'left' if cx < 0.33 else 'right' if cx > 0.66 else 'centre'
    return 'centre' if (v, h) == ('middle', 'centre') else f'{v} {h}' if v != 'middle' else h if h != 'centre' else v


def grounded_text(r, mask, img, rng):
    if r['label'] == 0:
        return 'This image is real. No manipulated region was found; the content is consistent with an unedited photograph.'
    t = TYPES[r['type']]
    out = ['This image is fake.', TYPE_TEXT[t]]
    if t in ('img2img', 'generated'):
        out.append('Because the whole face was produced by the model, there is no single edited region; '
                   'the evidence is spread over the skin texture, hair and background.')
    elif mask.any():
        pct = 100 * mask.mean()
        if r['face']:
            from explain.face_parts import part_masks
            parts = part_masks(img)[0]
            hit = [p for p, m in parts.items() if m.any() and (mask & m).sum() / m.sum() > 0.3]
            out.append(f'The manipulated region covers the {_join(hit)}, about {pct:.0f}% of the face crop.' if hit else
                       f'The manipulated region covers about {pct:.0f}% of the face crop.')
        else:
            out.append(f'The tampered area is in the {_position(mask)} of the image and covers about {pct:.0f}% of it.')
    return ' '.join(out)


def mmtd_texts(path):
    out = {}
    for e in json.load(open(path)):
        out[os.path.splitext(os.path.basename(e['image']))[0]] = e['conversations'][1]['value']
    return out


def main(args):
    rng = random.Random(args.seed)
    roots = dict(kv.split('=', 1) for kv in args.roots)
    recs = load_index(args.index, args.split)
    mmtd = mmtd_texts(args.mmtd) if args.mmtd else {}
    ds = ForgeryDataset(recs, roots, train=False, filter_p=0.0)
    conv, n_mmtd = [], 0
    for i, r in enumerate(recs):
        stem = os.path.splitext(os.path.basename(r['image']))[0]
        if r['source'] in ('casia', 'sd_inpaint') and stem in mmtd:
            answer, n_mmtd = mmtd[stem], n_mmtd + 1
        elif r['source'] in ('casia', 'sd_inpaint') and not args.grounded_fallback:
            continue
        else:
            from PIL import Image
            item = ds[i]
            img = Image.fromarray(((item['pixel'].numpy().transpose(1, 2, 0) * ds_std + ds_mean) * 255).clip(0, 255).astype(np.uint8))
            answer = grounded_text(r, item['forg'][0].numpy() > 0.5, img, rng)
        conv.append({'id': f"{r['source']}_{i}", 'root': r['root'], 'image': r['image'], 'box': r.get('box'),
                     'conversations': [{'from': 'human', 'value': '<image>\n<deepfake>\n' + rng.choice(QUESTIONS)},
                                       {'from': 'gpt', 'value': answer}]})
    os.makedirs(os.path.dirname(args.out) or '.', exist_ok=True)
    json.dump(conv, open(args.out, 'w'), indent=1)
    print(f'{len(conv)} conversations ({n_mmtd} MMTD, {len(conv) - n_mmtd} grounded) -> {args.out}')


from forensics.data import CLIP_MEAN as ds_mean, CLIP_STD as ds_std  # noqa: E402

if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--index', nargs='+', required=True)
    ap.add_argument('--roots', nargs='+', required=True)
    ap.add_argument('--mmtd', default=None)
    ap.add_argument('--split', default='train')
    ap.add_argument('--grounded-fallback', action='store_true', help='grounded text for CASIA/SD items without MMTD text')
    ap.add_argument('--out', required=True)
    ap.add_argument('--seed', type=int, default=0)
    main(ap.parse_args())
