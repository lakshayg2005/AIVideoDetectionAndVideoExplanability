"""Teacher descriptions for Stage-C training texts, written by a local open VLM (Qwen2.5-VL), run in the separate
`vlm` environment (newer transformers than the M2F2 stack).

The teacher is told what the manipulation is and, where a ground-truth mask exists, sees the region as a red box.
It must name exactly what is inside the box and list only clearly visible artifacts, as JSON. These texts are
model-written (like MMTD-Set's GPT-4o and FakeClue's descriptions) and are marked as such in the report.

conda run -n vlm python explain/teacher_annotate.py --samples ../data/teacher/samples.json --out ../data/teacher/teacher.jsonl
"""
import argparse
import json
import os
import re

import torch
from PIL import Image, ImageDraw

PROMPTS = {
    'ai_face': ('This image was generated or fully re-rendered by an AI image generator. Look closely at this specific '
                'image. Which single part of it looks most artificial, and what exactly is wrong with it? If nothing '
                'looks wrong, say that the evidence is subtle.'),
    'face_edit': ('The region inside the red box was regenerated by an AI inpainting model to change the face '
                  '(requested change: {edit}). Say precisely which facial feature or part is inside the red box.'),
    'splice': ('The content inside the red box was pasted in from another image or copied from elsewhere in this '
               'image. Name precisely what is inside the red box (be specific, e.g. "the face of the cat" rather '
               'than "the cat").'),
    'scene_inpaint': ('The region inside the red box was regenerated by an AI inpainting model. Name precisely what '
                      'is inside the red box.'),
}
FORMAT_BOX = (' Do not mention the red box. Answer only with JSON: {"region": "<what is inside the red box, a short noun '
              'phrase>", "artifacts": "<one short sentence naming a flaw you can actually see there, such as a blurred '
              'or sharp seam, mismatched texture, lighting or color, or a distorted shape; write \\"none visible\\" if '
              'you cannot see one. Do not describe the scene.>"}')
FORMAT_NOBOX = (' Answer only with JSON: {"region": "<the part that looks most artificial, a short noun phrase, or '
                'null>", "artifacts": "<one short sentence about that part; do not list parts that look fine>"}')
DRAWN_BOX = re.compile(r'\b(red|bounding|highlighted|marked)\s+(box|rectangle)\b|^(the\s+)?box$', re.I)
NONE_VISIBLE = ('none visible', 'no visible', 'not visible', 'cannot see', 'no artifact', 'no clear')


def load_image(s, max_side=768):
    img = Image.open(s['image']).convert('RGB')
    if s.get('box'):
        d = ImageDraw.Draw(img)
        w = max(2, min(img.size) // 120)
        d.rectangle(s['box'], outline=(255, 0, 0), width=w)
    if max(img.size) > max_side:
        f = max_side / max(img.size)
        img = img.resize((round(img.size[0] * f), round(img.size[1] * f)), Image.BICUBIC)
    return img


def parse(text):
    """region / artifacts from the teacher's JSON; anything about the red box itself is dropped, and "none visible"
    becomes None so that no artifact is invented downstream."""
    m = re.search(r'\{.*\}', text, re.S)
    try:
        d = json.loads(m.group(0)) if m else {}
    except json.JSONDecodeError:
        d = {}
    region = d.get('region')
    region = region.strip() if isinstance(region, str) and region.strip().lower() not in ('', 'null', 'none') else None
    if region and DRAWN_BOX.search(region):
        region = None
    artifacts = d.get('artifacts') if isinstance(d.get('artifacts'), str) else ''
    artifacts = ' '.join(x for x in re.split(r'(?<=[.!?])\s+', artifacts.strip()) if not DRAWN_BOX.search(x))
    if not artifacts or any(k in artifacts.lower() for k in NONE_VISIBLE):
        artifacts = None
    return region, artifacts


def main(args):
    from transformers import AutoProcessor, Qwen2_5_VLForConditionalGeneration
    samples = json.load(open(args.samples))
    done = set()
    if os.path.exists(args.out):
        done = {json.loads(l)['key'] for l in open(args.out)}
    todo = [s for s in samples if s['key'] not in done][:args.limit or None]
    print(f'{len(todo)} to annotate ({len(done)} done)', flush=True)
    model = Qwen2_5_VLForConditionalGeneration.from_pretrained(args.model, torch_dtype=torch.float16, device_map='cuda',
                                                              attn_implementation='sdpa').eval()
    proc = AutoProcessor.from_pretrained(args.model, min_pixels=256 * 28 * 28, max_pixels=768 * 28 * 28)
    proc.tokenizer.padding_side = 'left'
    with open(args.out, 'a') as f:
        for i in range(0, len(todo), args.bs):
            batch = todo[i:i + args.bs]
            imgs = [load_image(s) for s in batch]
            texts = []
            for s in batch:
                q = PROMPTS[s['task']].format(edit=s.get('edit') or 'unknown') + (FORMAT_BOX if s.get('box') else FORMAT_NOBOX)
                msg = [{'role': 'user', 'content': [{'type': 'image'}, {'type': 'text', 'text': q}]}]
                texts.append(proc.apply_chat_template(msg, tokenize=False, add_generation_prompt=True))
            inputs = proc(text=texts, images=imgs, return_tensors='pt', padding=True).to('cuda')
            with torch.no_grad():
                gen = model.generate(**inputs, max_new_tokens=args.max_new_tokens, do_sample=False)
            outs = proc.batch_decode(gen[:, inputs['input_ids'].shape[1]:], skip_special_tokens=True)
            for s, o in zip(batch, outs):
                region, artifacts = parse(o)
                f.write(json.dumps({'key': s['key'], 'task': s['task'], 'region': region, 'artifacts': artifacts,
                                    'raw': o.strip(), 'teacher': os.path.basename(args.model.rstrip('/'))}) + '\n')
            f.flush()
            print(f'{min(i + args.bs, len(todo))}/{len(todo)}', flush=True)


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--samples', default='../data/teacher/samples.json')
    ap.add_argument('--out', default='../data/teacher/teacher.jsonl')
    ap.add_argument('--model', default='Qwen/Qwen2.5-VL-3B-Instruct')
    ap.add_argument('--bs', type=int, default=8)
    ap.add_argument('--max-new-tokens', type=int, default=120)
    ap.add_argument('--limit', type=int, default=0)
    main(ap.parse_args())
